/*==================================================================================================
 *  src/main.c —— 入口（只做两件事）
 *
 *  【现在这个文件有多薄】
 *      EcuM_Init()      板级 + BSW 初始化 + 启动控制器
 *      EcuM_StartOS()   创建任务 + 启动调度器
 *
 *  【为什么能这么薄】
 *  因为我们一路把职责下放了：
 *
 *      ┌──────────────────────────────────────────────────────────┐
 *      │ Application/    车窗控制业务逻辑（状态机 + 安全规则）            │
 *      ├──────────────────────────────────────────────────────────┤
 *      │ Rte/            端口名字 ↔ COM 信号 ID                      │
 *      ├──────────────────────────────────────────────────────────┤
 *      │ Services/       Com（信号↔字节）、PduR（路由）、EcuM（启动）     │
 *      ├──────────────────────────────────────────────────────────┤
 *      │ EcuAbstraction/ CanIf（PduId ↔ Hth + CanId）              │
 *      ├──────────────────────────────────────────────────────────┤
 *      │ Mcal/           Can（Hth ↔ 控制器 + 邮箱）                  │
 *      ├──────────────────────────────────────────────────────────┤
 *      │ generate/ board/  CT 生成的硬件配置（时钟/引脚/位率/中断）       │
 *      ├──────────────────────────────────────────────────────────┤
 *      │ RTD/            NXP 驱动源码                               │
 *      └──────────────────────────────────────────────────────────┘
 *
 *  【真实项目里 main 也差不多这么薄】
 *  通常只剩 EcuM_Init() / EcuM_StartOS()，或者由启动代码直接调 EcuM。
 *================================================================================================*/

#include "ecum.h"

int main(void)
{
    /* 阶段一：板级 + BSW 初始化（内部顺序见 ecum.c） */
    EcuM_Init();

    /* 阶段二：创建 OS 任务并启动调度器（正常不返回） */
    EcuM_StartOS();

    /* 只有启动失败（例如堆不够）才会到这里 */
    for (;;)
    {
    }
}
